#!/usr/bin/env python3
"""Generate the 100-component DI graph for every framework from graph.json.

    python3 di/generate.py            # (re)write every framework's sources
    python3 di/generate.py --check    # exit 1 when a committed file is stale

One description (graph.json), six emitters, so every framework wires the same
graph: primavera (the language's compile-time DI that primavera builds on),
Spring, Quarkus (ArC), Micronaut, ASP.NET Core DI (Microsoft.Extensions.
DependencyInjection) and FastAPI `Depends`. Each entry resolves the ten
level-0 components, sums their value(), and prints

    components=<instances constructed> checksum=<sum>

which the harness reads off stdout (exec to that line is the measurement) and
checks against `expected()` below.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BENCH = os.path.dirname(HERE)
GRAPH = json.load(open(os.path.join(HERE, "graph.json")))
L = GRAPH["levels"]
W = GRAPH["width"]
FAN = GRAPH["fanout"]
HEADER = "Generated by bench/di/generate.py from bench/di/graph.json; do not edit."


def name(l, j):
    return f"C{l}{j}"


def deps(l, j):
    if l + 1 >= L:
        return []
    return [(l + 1, (j + d) % W) for d in FAN]


def ordinal(l, j):
    return W * l + j + 1


def expected():
    memo = {}

    def value(l, j):
        if (l, j) not in memo:
            memo[(l, j)] = ordinal(l, j) + sum(value(a, b) for a, b in deps(l, j))
        return memo[(l, j)]

    return L * W, sum(value(0, j) for j in range(W))


ALL = [(l, j) for l in range(L) for j in range(W)]
ROOTS = [(0, j) for j in range(W)]


def var(l, j):
    return f"c{l}{j}"


# ---- Java (Spring, Quarkus, Micronaut) ------------------------------------

JAVA_ANN = {
    "spring": ("import org.springframework.stereotype.Component;\n", "@Component"),
    "quarkus": ("import jakarta.inject.Inject;\nimport jakarta.inject.Singleton;\n", "@Singleton"),
    "micronaut": ("import jakarta.inject.Singleton;\n", "@Singleton"),
}


def java_component(fw, l, j):
    imports, ann = JAVA_ANN[fw]
    ds = deps(l, j)
    fields = "".join(f"    private final {name(*d)} {var(*d)};\n" for d in ds)
    params = ", ".join(f"{name(*d)} {var(*d)}" for d in ds)
    assigns = "".join(f"        this.{var(*d)} = {var(*d)};\n" for d in ds)
    ctor_ann = "    @Inject\n" if fw == "quarkus" and ds else ""
    total = " + ".join([str(ordinal(l, j))] + [f"{var(*d)}.value()" for d in ds])
    return (f"// {HEADER}\npackage bench.di;\n\n{imports}\n{ann}\npublic class {name(l, j)} {{\n"
            f"{fields}\n{ctor_ann}    public {name(l, j)}({params}) {{\n{assigns}"
            f"        Counter.COUNT.incrementAndGet();\n    }}\n\n"
            f"    public long value() {{\n        return {total};\n    }}\n}}\n")


JAVA_COUNTER = (f"// {HEADER}\npackage bench.di;\n\nimport java.util.concurrent.atomic.AtomicInteger;\n\n"
                "/** Instances constructed so far; each component's constructor counts itself. */\n"
                "public final class Counter {\n    public static final AtomicInteger COUNT = new AtomicInteger();\n\n"
                "    private Counter() {\n    }\n}\n")


def java_sum(get):
    return " + ".join(get(r) for r in ROOTS)


def java_main(fw):
    if fw == "spring":
        s = java_sum(lambda r: f"ctx.getBean({name(*r)}.class).value()")
        return (f"// {HEADER}\npackage bench.di;\n\n"
                "import org.springframework.boot.Banner;\nimport org.springframework.boot.SpringApplication;\n"
                "import org.springframework.boot.WebApplicationType;\n"
                "import org.springframework.boot.autoconfigure.SpringBootApplication;\n"
                "import org.springframework.context.ConfigurableApplicationContext;\n\n"
                "/** Starts the context with no web server, then makes the first injected call. */\n"
                "@SpringBootApplication\npublic class DiMain {\n"
                "    public static void main(String[] args) {\n"
                "        SpringApplication app = new SpringApplication(DiMain.class);\n"
                "        app.setWebApplicationType(WebApplicationType.NONE);\n"
                "        app.setBannerMode(Banner.Mode.OFF);\n"
                "        ConfigurableApplicationContext ctx = app.run(args);\n"
                f"        long sum = {s};\n"
                "        System.out.println(\"components=\" + Counter.COUNT.get() + \" checksum=\" + sum);\n"
                "        System.out.flush();\n        ctx.close();\n        System.exit(0);\n    }\n}\n")
    if fw == "quarkus":
        fields = "".join(f"    @Inject\n    {name(*r)} {var(*r)};\n\n" for r in ROOTS)
        s = java_sum(lambda r: f"{var(*r)}.value()")
        return (f"// {HEADER}\npackage bench.di;\n\n"
                "import io.quarkus.runtime.Quarkus;\nimport io.quarkus.runtime.QuarkusApplication;\n"
                "import io.quarkus.runtime.annotations.QuarkusMain;\nimport jakarta.inject.Inject;\n\n"
                "/** Command mode: ArC wires the graph, run() makes the first injected call. */\n"
                "@QuarkusMain\npublic class DiMain implements QuarkusApplication {\n"
                f"{fields}"
                "    public static void main(String... args) {\n        Quarkus.run(DiMain.class, args);\n    }\n\n"
                "    @Override\n    public int run(String... args) {\n"
                f"        long sum = {s};\n"
                "        System.out.println(\"components=\" + Counter.COUNT.get() + \" checksum=\" + sum);\n"
                "        System.out.flush();\n        return 0;\n    }\n}\n")
    s = java_sum(lambda r: f"ctx.getBean({name(*r)}.class).value()")
    return (f"// {HEADER}\npackage bench.di;\n\nimport io.micronaut.context.ApplicationContext;\n\n"
            "/** Starts the bean context with no server, then makes the first injected call. */\n"
            "public class DiMain {\n    public static void main(String[] args) {\n"
            "        try (ApplicationContext ctx = ApplicationContext.run()) {\n"
            f"            long sum = {s};\n"
            "            System.out.println(\"components=\" + Counter.COUNT.get() + \" checksum=\" + sum);\n"
            "            System.out.flush();\n        }\n        System.exit(0);\n    }\n}\n")


def java_files(fw):
    out = {f"{name(l, j)}.java": java_component(fw, l, j) for l, j in ALL}
    out["Counter.java"] = JAVA_COUNTER
    out["DiMain.java"] = java_main(fw)
    return out


# ---- C# (ASP.NET Core DI) --------------------------------------------------

def csharp_files():
    classes = []
    for l, j in ALL:
        ds = deps(l, j)
        fields = "".join(f"    private readonly {name(*d)} _{var(*d)};\n" for d in ds)
        params = ", ".join(f"{name(*d)} {var(*d)}" for d in ds)
        assigns = "".join(f"        _{var(*d)} = {var(*d)};\n" for d in ds)
        total = " + ".join([str(ordinal(l, j))] + [f"_{var(*d)}.Value()" for d in ds])
        classes.append(f"public sealed class {name(l, j)}\n{{\n{fields}\n    public {name(l, j)}({params})\n    {{\n"
                       f"{assigns}        Counter.Increment();\n    }}\n\n"
                       f"    public long Value() => {total};\n}}\n")
    regs = "".join(f"        services.AddSingleton<{name(l, j)}>();\n" for l, j in ALL)
    graph = (f"// {HEADER}\nusing System.Threading;\nusing Microsoft.Extensions.DependencyInjection;\n\n"
             "namespace Bench.Di;\n\n"
             "public static class Counter\n{\n    private static int _count;\n"
             "    public static int Count => Volatile.Read(ref _count);\n"
             "    public static void Increment() => Interlocked.Increment(ref _count);\n}\n\n"
             "public static class Graph\n{\n"
             "    public static IServiceCollection AddBenchGraph(this IServiceCollection services)\n    {\n"
             f"{regs}        return services;\n    }}\n}}\n\n" + "\n".join(classes))
    s = " + ".join(f"sp.GetRequiredService<{name(*r)}>().Value()" for r in ROOTS)
    program = (f"// {HEADER}\nusing System;\nusing Bench.Di;\nusing Microsoft.Extensions.DependencyInjection;\n\n"
               "// Builds the container, then makes the first injected call.\n"
               "var services = new ServiceCollection();\nservices.AddBenchGraph();\n"
               "using var sp = services.BuildServiceProvider();\n"
               f"long sum = {s};\n"
               "Console.WriteLine($\"components={Counter.Count} checksum={sum}\");\nConsole.Out.Flush();\n")
    return {"Graph.cs": graph, "Program.cs": program}


# ---- Python (FastAPI Depends) ----------------------------------------------

def python_files():
    lines = [f"# {HEADER}", '"""The graph as FastAPI dependencies: one result per component per request."""',
             "from fastapi import Depends", "", "COUNT = 0", "", "",
             "class Component:", "    __slots__ = (\"ordinal\", \"deps\")", "",
             "    def __init__(self, ordinal, *deps):", "        global COUNT", "        COUNT += 1",
             "        self.ordinal = ordinal", "        self.deps = deps", "",
             "    def value(self):", "        return self.ordinal + sum(d.value() for d in self.deps)", ""]
    for l, j in reversed(ALL):
        ds = deps(l, j)
        params = ", ".join(f"{var(*d)}=Depends({var(*d)}_dep)" for d in ds)
        args = "".join(f", {var(*d)}" for d in ds)
        lines += ["", f"def {var(l, j)}_dep({params}):", f"    return Component({ordinal(l, j)}{args})", ""]
    graph = "\n".join(lines) + "\n"
    roots = ", ".join(f"{var(*r)}=Depends(graph.{var(*r)}_dep)" for r in ROOTS)
    s = " + ".join(f"{var(*r)}.value()" for r in ROOTS)
    main = (f"# {HEADER}\n"
            '"""Builds the FastAPI app, then makes the first injected call: one request\n'
            'through the ASGI interface (no server), whose endpoint depends on the ten\n'
            'level-0 components."""\n'
            "import asyncio\nimport json\nimport sys\n\nfrom fastapi import Depends, FastAPI\n\nimport graph\n\n"
            "app = FastAPI()\n\n\n@app.get(\"/di\")\n"
            f"def di({roots}):\n    return {{\"components\": graph.COUNT, \"checksum\": {s}}}\n\n\n"
            "async def first_call():\n    sent = []\n\n"
            "    async def receive():\n        return {\"type\": \"http.request\", \"body\": b\"\", \"more_body\": False}\n\n"
            "    async def send(message):\n        sent.append(message)\n\n"
            "    scope = {\"type\": \"http\", \"asgi\": {\"version\": \"3.0\"}, \"http_version\": \"1.1\",\n"
            "             \"method\": \"GET\", \"scheme\": \"http\", \"path\": \"/di\", \"raw_path\": b\"/di\",\n"
            "             \"root_path\": \"\", \"query_string\": b\"\", \"headers\": [],\n"
            "             \"client\": (\"127.0.0.1\", 1), \"server\": (\"127.0.0.1\", 80)}\n"
            "    await app(scope, receive, send)\n"
            "    body = b\"\".join(m.get(\"body\", b\"\") for m in sent if m[\"type\"] == \"http.response.body\")\n"
            "    return json.loads(body)\n\n\n"
            "if __name__ == \"__main__\":\n    r = asyncio.run(first_call())\n"
            "    print(f\"components={r['components']} checksum={r['checksum']}\", flush=True)\n    sys.exit(0)\n")
    return {"graph.py": graph, "main.py": main}


# ---- Cajeta (the language's compile-time DI, which primavera builds on) ----

def cajeta_files():
    out = {}
    for l, j in ALL:
        ds = deps(l, j)
        fields = "".join(f"    @Inject {name(*d)} {var(*d)};\n" for d in ds)
        total = " + ".join([f"(int64) {ordinal(l, j)}"] + [f"this.{var(*d)}.value()" for d in ds])
        out[f"{name(l, j)}.cajeta"] = (
            f"// {HEADER}\npackage bench.primavera.di;\n\n@Component\npublic class {name(l, j)} {{\n{fields}\n"
            f"    public {name(l, j)}() {{\n        Counter.count = Counter.count + 1;\n        return;\n    }}\n\n"
            f"    public int64 value() {{\n        return {total};\n    }}\n}}\n")
    out["Counter.cajeta"] = (f"// {HEADER}\npackage bench.primavera.di;\n\n"
                             "/** Instances constructed so far; each component's constructor counts itself. */\n"
                             "public final class Counter {\n    public static int32 count = 0;\n}\n")
    s = " + ".join(f"{name(*r)}.__cajeta_inject().value()" for r in ROOTS)
    out["DiMain.cajeta"] = (f"// {HEADER}\npackage bench.primavera.di;\n\n"
                            "/** The compiler wired the graph at build; the first injected call builds it. */\n"
                            "public final class DiMain {\n    public static int32 main(String[] args) {\n"
                            f"        int64 sum = {s};\n"
                            "        System.stdout.println(\"components=\" + Counter.count + \" checksum=\" + sum);\n"
                            "        return 0;\n    }\n}\n")
    return out


TARGETS = {
    "apps/di/src/main/cajeta/bench/primavera/di": cajeta_files,
    "competitors/spring-boot/di/src/main/java/bench/di": lambda: java_files("spring"),
    "competitors/quarkus/di/src/main/java/bench/di": lambda: java_files("quarkus"),
    "competitors/micronaut/di/src/main/java/bench/di": lambda: java_files("micronaut"),
    "competitors/aspnetcore/di": csharp_files,
    "competitors/fastapi/di": python_files,
}


def main():
    check = "--check" in sys.argv
    stale = 0
    for rel, emit in TARGETS.items():
        d = os.path.join(BENCH, rel)
        os.makedirs(d, exist_ok=True)
        for fname, text in emit().items():
            p = os.path.join(d, fname)
            old = open(p).read() if os.path.exists(p) else None
            if old == text:
                continue
            if check:
                print(f"stale: {os.path.relpath(p, BENCH)}")
                stale += 1
            else:
                with open(p, "w", newline="\n") as f:
                    f.write(text)
    n, s = expected()
    print(f"expected: components={n} checksum={s}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
